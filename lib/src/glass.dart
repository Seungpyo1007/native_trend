      'wrong. Do not guess widget names.',
    )
    ..writeln(
      '- If the package falls back on other platforms by itself, use its '
      'widgets everywhere. Otherwise branch on '
      '`defaultTargetPlatform == TargetPlatform.macOS` (safe on web, unlike '
      '`dart:io` Platform) and keep the existing widgets elsewhere.',
    )
    ..writeln(
      '- Platform views on macOS do not take Flutter gestures or keyboard '
      'focus, and each one costs an extra surface. Use them for controls and '
