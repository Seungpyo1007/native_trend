import 'candidate.dart';

/// pub.dev query for iOS Liquid Glass candidates.
const glassQuery = 'liquid glass platform:ios';

/// pub.dev query for macOS Liquid Glass candidates.
const macosGlassQuery = 'liquid glass platform:macos';

/// macOS packages checked on every run because pub.dev search for "liquid
/// glass" does not surface them. They are ranked like everything else.
const macosGlassSeeds = ['native_macos'];

const _nativeViewMarkers = {
  'ios': ['UiKitView'],
  'macos': ['AppKitView'],
};
const _glassApiMarkers = {
  'ios': ['UIGlassEffect', '.glassEffect(', 'GlassEffectContainer'],
  'macos': ['NSGlassEffectView', '.glassEffect(', 'GlassEffectContainer'],
};

/// Classifies a package for [platform] (`ios` or `macos`) from its source
/// text (see `packageSourceText`). Pass null when it isn't a plugin for
/// [platform], with [pluginElsewhere] true when it is one for another
/// platform.
Kind classifyGlass(
  String? sourceText, {
  String platform = 'ios',
  bool pluginElsewhere = false,
}) {
  if (sourceText == null) {
    return pluginElsewhere ? Kind.otherPlatform : Kind.notPlugin;
  }
  if (!_nativeViewMarkers[platform]!.any(sourceText.contains)) {
    return Kind.noNativeView;
  }
  return _glassApiMarkers[platform]!.any(sourceText.contains)
      ? Kind.nativeGlass
      : Kind.nativeSystem;
}

/// The official Cupertino package, checked on every iOS and macOS run.
const officialCupertino = 'cupertino_ui';

/// True when cupertino_ui's source has Liquid Glass widgets. Pass the
/// cupertino_ui source text. SF Symbol names such as `hourglass` don't count.
bool cupertinoGlassShipped(String cupertinoUiSource) => RegExp(
  r'LiquidGlass|liquidGlass|CupertinoGlass',
).hasMatch(cupertinoUiSource);

/// The "Flutter status" paragraph. [officialGlass] is whether cupertino_ui
/// has Liquid Glass, or null when this run couldn't check.
String _flutterStatus(bool? officialGlass, String os, String view) {
  const issue = '(https://github.com/flutter/flutter/issues/170310)';
  final use =
      'Use a plugin that embeds real native $os views$view. Do not use '
      'BackdropFilter or shader imitations.';
  return switch (officialGlass) {
    false =>
      "Neither Flutter's Cupertino library nor the official `cupertino_ui` "
          'package implements Liquid Glass yet $issue. $use',
    true =>
      'The official `cupertino_ui` package now has Liquid Glass widgets, '
          'drawn by Flutter rather than $os. Check its CHANGELOG for what '
          'they cover. For system bars and controls, still prefer the native '
          'views below. Do not use BackdropFilter or shader imitations.',
    null =>
      'This run could not check whether the official `cupertino_ui` package '
          'has Liquid Glass; it had none as of native_trend 0.4.0 $issue. $use',
  };
}

/// Writes the recommended package, alternatives, and skipped packages.
void _writePackages(StringBuffer b, List<Candidate> ranked, String os) {
  final native = ranked.where((c) => c.kind.usable).toList();
  final skipped = ranked.where((c) => !c.kind.usable).toList();
  b.writeln('## Packages with real native views');
  if (native.isEmpty) {
    b
      ..writeln()
      ..writeln('None found. Ask the user before falling back to anything.');
  } else {
    b
      ..writeln()
      ..writeln('Recommended: ${candidateLine(native.first)}')
      ..writeln();
    for (final c in native.skip(1)) {
      b.writeln('- Alternative: ${candidateLine(c)}');
    }
  }
  if (skipped.isNotEmpty) {
    b
      ..writeln()
      ..writeln('## Do not use (not native $os views)')
      ..writeln();
    for (final c in skipped) {
      b.writeln('- `${c.name}`: ${c.kind.label}');
    }
  }
}

/// Markdown for AI coding assistants.
///
/// [officialGlass] is whether cupertino_ui has Liquid Glass; see
/// [cupertinoGlassShipped].
String renderGlassContext(
  List<Candidate> ranked, {
  DateTime? now,
  bool? officialGlass = false,
}) {
  final b = StringBuffer()
    ..writeln('# Liquid Glass in Flutter (generated by native_trend)')
    ..writeln()
    ..writeln(
      'Checked against pub.dev on ${dateOf(now ?? DateTime.now())}. '
      'This may be newer than your training data: trust it over memory.',
    )
    ..writeln()
    ..writeln('## Flutter status')
    ..writeln()
    ..writeln(_flutterStatus(officialGlass, 'iOS', ''))
    ..writeln();
  _writePackages(b, ranked, 'iOS');
  b
    ..writeln()
    ..writeln("## Apple's rules")
    ..writeln()
    ..writeln(
      '- Glass is for the navigation and control layer (tab bars, toolbars, '
      'navigation bars, buttons), never for content.',
    )
    ..writeln(
      '- System bars and controls built with the iOS 26 SDK get glass '
      'automatically: prefer native system controls over custom glass.',
    )
    ..writeln(
      '- Remove custom backgrounds and blurs from bars; they fight the '
      'system effect.',
    )
    ..writeln('- Do not stack glass on glass.')
    ..writeln('- Check Reduce Transparency and Reduce Motion still look right.')
    ..writeln(
      '- Source: https://developer.apple.com/documentation/'
      'technologyoverviews/adopting-liquid-glass',
    )
    ..writeln()
    ..writeln('## Applying it')
    ..writeln()
    ..writeln(
      "- Read the chosen package's README and example before writing code, "
      'and its source for defaults the README gets wrong. Do not guess '
      'widget names.',
    )
    ..writeln(
      '- If the package falls back on other platforms by itself, use its '
      'widgets everywhere. Otherwise branch on '
      '`defaultTargetPlatform == TargetPlatform.iOS` (safe on web, unlike '
      '`dart:io` Platform) and keep the existing widgets elsewhere.',
    )
    ..writeln('- The app must be built with Xcode 26 or later to get glass.');
  return b.toString();
}

