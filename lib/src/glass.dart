      '- Remove custom title bar and sidebar backgrounds and blurs; they '
      'fight the system effect.',
    )
    ..writeln('- Do not stack glass on glass.')
    ..writeln(
      '- Check Reduce Transparency, Increase Contrast, and both light and '
      'dark appearance still look right.',
    )
    ..writeln(
      '- Source: https://developer.apple.com/documentation/'
      'technologyoverviews/adopting-liquid-glass',
    )
    ..writeln()
    ..writeln('## Applying it')
    ..writeln()
